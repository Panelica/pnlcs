<h2>1.a. Kanuni cayma hakkınız</h2>
<p>Tüketici sıfatını taşıyorsanız 6502 sayılı Kanun ve Mesafeli Sözleşmeler Yönetmeliği size ayrıca <strong>14 günlük cayma hakkı</strong> tanır. Ancak Yönetmeliğin 15. maddesi, elektronik ortamda anında ifa edilen hizmetleri ve sizin onayınızla ifasına başlanan hizmetleri bu hakkın dışında tutar; barındırma ve alan adı hizmetleri, siparişiniz onaylanır onaylanmaz açıldığı için bu kapsama girer.</p>
<p>Yukarıdaki para iade güvencesini <strong>tam da bu yüzden</strong> veriyoruz: kanunen zorunlu olmadığı hâlde, hizmeti deneyip vazgeçme imkânını sözleşmeyle taahhüt ediyoruz. Yıllık pakette tanıdığımız 30 gün, kanuni 14 günün iki katından fazladır.</p>
<p>Somut olayda kanuni cayma hakkınızın doğduğu ve istisnaya girmediği hâllerde, bu politika o hakkı hiçbir şekilde sınırlandırmaz; hangisi sizin lehinizeyse o uygulanır.

