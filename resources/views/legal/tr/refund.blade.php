<h2>3. Süre geçtikten sonra: dönem ortası iptal</h2>
<p>Yukarıdaki iade süresi geçtikten sonra hizmetinizi dilediğiniz an iptal edebilirsiniz. Bu durumda:</p>
<ul>
    <li>Hizmet, ödemesi yapılmış dönemin <strong>sonuna kadar çalışmaya devam eder</strong>; dönem bitiminde kapanır.</li>
    <li>Kullanılmamış döneme ait <strong>orantılı iade yapılmaz;</strong> ancak dilerseniz kalan tutarı hesabınızda kredi olarak tutar, başka hizmetlerde kullanabilirsiniz.</li>
    <li>Bir sonraki dönem için fatura kesilmez.</li>
</ul>

<h2>4. Bizden kaynaklanan hâller</h2>
<p>Aşağıdaki durumlarda, iade süresi geçmiş olsa dahi <strong>kullanılmamış döneme ait bedeli orantılı olarak iade ederiz:</strong></p>
<ul>
    <li>Satın aldığınız hizmeti sunamıyorsak veya taahhüt ettiğimiz özellikleri sağlayamıyorsak,</li>
