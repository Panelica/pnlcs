<p>Bu politika, sunucularımızda ve ağımızda neyin yapılabileceğini, neyin yapılamayacağını belirler. Amacı basittir: bir müşterinin davranışı diğerlerinin hizmetini, sunucularımızın güvenliğini veya IP itibarımızı bozmasın. Politika, <a href="{{ route('legal.show', 'terms') }}">Kullanım Koşulları</a>'nın ayrılmaz parçasıdır ve hizmetlerimizin tamamı için geçerlidir.</p>

<h2>1. Yasak içerik ve faaliyetler</h2>
<p>Aşağıdakiler her koşulda yasaktır:</p>
<ul>
    <li><strong>Çocuk istismarı içeriği.</strong> Tespit edilmesi hâlinde hizmet uyarısız kapatılır ve durum yetkili makamlara bildirilir.</li>
    <li><strong>Telif ihlali.</strong> Hak sahibinin izni olmayan yazılım, film, müzik, kitap, oyun veya lisans anahtarı dağıtımı.</li>
    <li><strong>Kimlik avı (phishing), dolandırıcılık ve sahte kurum siteleri.</strong> Banka, kamu kurumu, kargo şirketi veya başka bir markanın taklidi.</li>
    <li><strong>Zararlı yazılım.</strong> Virüs, truva atı, fidye yazılımı, keylogger, botnet paneli, exploit kiti barındırmak veya dağıtmak.</li>
    <li><strong>Yetkisiz erişim faaliyetleri.</strong> Port taraması, kaba kuvvet saldırısı, zafiyet istismarı, şifre kırma; sunucumuzdan başka sistemlere ya da başka sistemlerden bize yönelik.</li>
    <li><strong>Servis dışı bırakma (DoS/DDoS) saldırıları</strong> ve bu saldırılara aracılık eden yansıtma/güçlendirme servisleri.</li>
    <li><strong>Terör propagandası,</strong> şiddete tahrik, nefret söylemi ve suç işlemeye teşvik.</li>
    <li><strong>Yasa dışı kumar, uyuşturucu ticareti, silah ticareti, sahte belge üretimi</strong> ve ilgili mevzuata aykırı diğer faaliyetler.</li>
    <li><strong>Türkiye Cumhuriyeti mevzuatına aykırı her türlü içerik,</strong> 5651 sayılı Kanun kapsamındaki katalog suçlar dâhil.</li>
</ul>

<h2>2. E-posta ve toplu gönderim</h2>
<p>IP itibarımız bütün müşterilerimizin ortak varlığıdır. Bu nedenle:</p>
<ul>
    <li><strong>İstenmeyen e-posta (spam) kesinlikle yasaktır.</strong> Satın alınmış, kazınmış (scraped) veya devralınmış listelere gönderim yapılamaz.</li>
    <li>Toplu gönderim yapacaksanız alıcıların <strong>açık onayının</strong> (opt-in) bulunması ve bu onayı belgeleyebilmeniz gerekir.</li>
    <li>Her toplu e-postada <strong>çalışan bir abonelikten çıkma bağlantısı</strong> bulunmalıdır.</li>
    <li>Gönderen adresi, alan adı veya başlık bilgilerini yanıltıcı biçimde değiştirmek yasaktır.</li>
    <li>Paketlerde saatlik gönderim sınırları uygulanır. Sınırın üzerinde düzenli gönderim ihtiyacınız varsa, ölçeğe uygun bir çözüm için önceden bize yazın.</li>
</ul>
<p>Şikâyet oranınızın yükselmesi veya bir kara listeye girmemize yol açacak bir davranış tespit edilmesi hâlinde, gönderim yetkiniz derhâl kısıtlanabilir.</p>

<h2>3. Kaynak kullanımı</h2>
<p>Her hesap kendi ayrılmış işlemci, bellek ve disk sınırları içinde çalışır ve bu sınırlar çekirdek düzeyinde uygulanır. Buna rağmen aşağıdakiler paylaşımlı barındırmada yasaktır:</p>
<ul>
    <li>Kripto para madenciliği ve benzeri sürekli tam kapasite işlemci tüketen işler,</li>
    <li>Genel amaçlı dosya depolama, yedek deposu veya medya arşivi olarak kullanım (barındırdığınız siteyle ilgisi olmayan içerik),</li>
    <li>Torrent tohumlama (seeding), açık proxy, açık VPN çıkışı, TOR çıkış düğümü,</li>
    <li>Hesabın dışına çıkmayı deneyen, çekirdek veya panel zafiyetlerini araştıran işlemler.</li>
</ul>
<p>Bir işin diğer müşterileri etkilediğini tespit edersek önce sizinle iletişime geçer, mümkünse birlikte çözüm ararız. Etki acil ve ağırsa, süreç sonrasında bildirilmek üzere ilgili işlem geçici olarak durdurulabilir.</p>

<h2>4. Güvenlik yükümlülükleriniz</h2>
<ul>
    <li>Uygulama, tema ve eklentilerinizi güncel tutun. Ele geçirilen hesapların büyük çoğunluğu güncellenmemiş yazılımdan kaynaklanır.</li>
    <li>Güçlü ve benzersiz şifreler kullanın; mümkün olan her yerde iki adımlı doğrulamayı açın.</li>
    <li>Hesabınızın ele geçirildiğinden şüpheleniyorsanız gecikmeden bize bildirin.</li>
    <li>Sunucularımızda güvenlik testi yapmak istiyorsanız <strong>önceden yazılı izin alın.</strong> İzinsiz test, saldırı olarak değerlendirilir.</li>
</ul>

