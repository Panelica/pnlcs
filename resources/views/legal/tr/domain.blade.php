<h2>1. Üst kuralların bağlayıcılığı</h2>
<p>Bir alan adı kaydettirdiğinizde yalnızca bizimle değil, ilgili tescil kuruluşu ve uzantıyı işleten registry ile de bir ilişki kurmuş olursunuz. Bu nedenle:</p>
<ul>
    <li>ICANN'in tescil ettirenlere ilişkin politikaları,</li>
    <li>Uzantıyı işleten registry'nin kuralları (".com" için Verisign, ".tr" için TRABİS gibi),</li>
    <li>Yeknesak Alan Adı Uyuşmazlık Çözüm Politikası (UDRP) ve uygulanabilir hâllerde URS</li>
</ul>
<p>sizin için doğrudan bağlayıcıdır. Bu kurallar değiştiğinde biz de uymak zorundayız; bu değişiklikler üzerinde kontrolümüz yoktur.</p>

<h2>2. Tescil bilgileri ve doğruluk yükümlülüğü</h2>
<p>ICANN kuralları, tescil ettirenin <strong>doğru, eksiksiz ve güncel</strong> iletişim bilgisi vermesini zorunlu tutar.</p>
<ul>
    <li>Bilgilerinizin değişmesi hâlinde gecikmeden güncellemeniz gerekir.</li>
    <li>Kasten yanlış bilgi vermek veya doğrulama talebine <strong>15 gün</strong> içinde cevap vermemek, alan adının askıya alınmasına yol açar. Bu, ICANN'in bize yüklediği bir yükümlülüktür; takdirimizde değildir.</li>
    <li>Bazı uzantılarda e-posta adresinizin doğrulanması zorunludur. Doğrulama e-postasını yanıtlamazsanız alan adı çalışmaz hâle gelir.</li>
</ul>

<h2>3. WHOIS / RDDS</h2>
<p>Tescil bilgilerinizin bir bölümü, registry ve tescil kuruluşunun kamuya açık sorgu servislerinde (WHOIS/RDDS) yayımlanabilir. Hangi alanların görüneceği uzantıya ve yürürlükteki veri koruma kurallarına göre değişir; GDPR kapsamındaki gerçek kişilerde iletişim bilgileri çoğu uzantıda gizlenir.</p>
<p>Gizlilik koruması (privacy/proxy) hizmeti sunulan uzantılarda bu hizmeti talep edebilirsiniz. Gizlilik korumasının, hukuka uygun bir talep veya UDRP süreci hâlinde kaldırılabileceğini bilmelisiniz.</p>

