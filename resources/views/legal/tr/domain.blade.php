<h2>5. Ücretler</h2>
<p>Kayıt, yenileme ve transfer ücretleri sitemizde ilan edilir. Bu ücretler <strong>registry fiyatlarına ve döviz kuruna bağlı olarak değişebilir;</strong> registry bir zam açıkladığında yenileme fiyatınız da değişir. Fiyat değişikliklerini yenileme öncesinde bildiririz.</p>
<p>Alan adı bedelleri, kayıt anında geri alınamaz biçimde tescil kuruluşuna aktarıldığından <strong>iade edilmez</strong> — ayrıntı için <a href="{{ route('legal.show', 'refund') }}">İptal, Cayma ve İade Politikası</a>.</p>

<h2>6. Transfer</h2>
<p><strong>Bize transfer:</strong> Alan adının en az 60 günlük olması, kilidinin açık olması ve mevcut sağlayıcınızdan alacağınız yetkilendirme (EPP/Auth) koduna sahip olmanız gerekir. Transfer genellikle alan adına bir yıl süre ekler.</p>
<p><strong>Bizden transfer:</strong> Alan adınızı dilediğiniz zaman başka bir sağlayıcıya taşıyabilirsiniz. EPP kodunuzu panelinizden alabilir veya bizden talep edebilirsiniz; <strong>talebinizi 5 gün içinde karşılarız ve bunun için ücret almayız.</strong> Ödenmemiş faturanız yoksa transferi engellemeyiz.</p>
<p>ICANN kuralları gereği, kayıttan ve önceki bir transferden sonraki <strong>60 gün</strong> içinde transfer yapılamaz.</p>

<h2>7. Uyuşmazlıklar</h2>
<p>Alan adınızın bir markayı ihlal ettiği iddiasıyla size karşı UDRP süreci başlatılabilir. Bu süreç bizim tarafımızdan değil, ICANN'in yetkilendirdiği uyuşmazlık çözüm sağlayıcıları (örneğin WIPO) tarafından yürütülür.</p>
<p>UDRP veya mahkeme kararı doğrultusunda alan adının devri, iptali veya kilitlenmesi yönünde bir karar verilirse, kararı uygulamak zorundayız. ".tr" uzantılarında TRABİS'in uyuşmazlık çözüm mekanizması geçerlidir.</p>

<h2>8. Ad sunucuları</h2>
<p>Alan adınızın ad sunucularını (nameserver) dilediğiniz zaman değiştirebilirsiniz. Varsayılan olarak bizim ad sunucularımız tanımlanır. Ad sunucusu değişikliklerinin internet genelinde yayılması <strong>24–48 saat</strong> sürebilir; bu yayılma süresi bizim kontrolümüzde değildir.</p>

<h2>9. Sorumluluk</h2>
<p>Alan adı işlemlerindeki sorumluluğumuz, ilgili alan adı için bize ödediğiniz bedelle sınırlıdır. Registry veya tescil kuruluşunun kararlarından, ICANN politika değişikliklerinden ve uzantıya özgü kuralların uygulanmasından doğan sonuçlardan sorumlu değiliz.</p>
<p>Bir kayıt talebiniz teknik bir hata nedeniyle gerçekleşmezse ve alan adı bu sırada başkası tarafından alınırsa, sorumluluğumuz aldığımız bedelin iadesiyle sınırlıdır.</p>
