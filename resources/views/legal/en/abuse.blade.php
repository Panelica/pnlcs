<h2>1. What your report must contain</h2>
<ul>
    <li><strong>A full address.</strong> The direct URL of the content complained of. We cannot investigate "somewhere on that site".</li>
    <li><strong>The nature of the complaint.</strong> Copyright infringement, phishing, malware, spam, defamation, unlawful content.</li>
    <li><strong>An explanation.</strong> A short, concrete statement of why it is unlawful.</li>
    <li><strong>Your contact details.</strong> Name, email and the organisation you represent, if any.</li>
    <li><strong>Evidence.</strong> Screenshots, email headers (full headers are required for spam reports), log entries.</li>
</ul>
<p>We also consider anonymous reports, but if information is missing we cannot come back to you and the investigation is limited to what we have.</p>

<h2>2. Copyright complaints</h2>
<p>If you are a rights holder or an authorised agent, please also include:</p>
<ul>
    <li>a description of the work said to be infringed and, where available, the address of the original,</li>
    <li>a statement that you are the rights holder or authorised to act for one,</li>
    <li>a good-faith statement that the information is accurate and the use is not authorised by the rights holder,</li>
    <li>your physical or electronic signature.</li>
</ul>
<p>These elements correspond to what is required by 17 U.S.C. §512(c)(3) (DMCA) and by Additional Article 4 of Turkish Law No. 5846 on Intellectual and Artistic Works.</p>

<h3>Counter-notice</h3>
<p>If your content was removed following a copyright complaint and you believe that was wrong, you may send a counter-notice identifying the removed material, stating your good-faith belief that removal was a mistake, giving your contact details and consenting to jurisdiction. We pass the counter-notice to the complainant and, if no notice of proceedings reaches us within <strong>10 business days</strong>, we restore the content.</p>
<p>Knowingly filing a false report has legal consequences — for either side.</p>

<h2>3. Requests under Turkish Law No. 5651</h2>
<p>If you are resident in Türkiye and content infringes your personal rights, Article 9 of Law No. 5651 lets you apply first to the content provider and, where they cannot be reached, to us as the hosting provider. We assess such applications within <strong>24 hours</strong> and tell you the outcome.</p>
<p>Decisions of a criminal judgeship of peace or of the Information and Communication Technologies Authority are implemented within the period stated in the decision.</p>

