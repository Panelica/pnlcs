<h3>Exception: immediate action</h3>
<p>We act immediately, without prior notice to the customer, where we find:</p>
<ul>
    <li><strong>Child sexual abuse material</strong> — the account is terminated without notice and the matter referred to the authorities.</li>
    <li><strong>An active phishing page</strong> — people are being defrauded every minute it stays up.</li>
    <li><strong>Malware distribution</strong> or an ongoing attack originating from the account.</li>
    <li>An order from a competent authority requiring immediate action.</li>
</ul>

<h2>5. If the content reported is yours</h2>
<p>We tell you when a report concerns you. If you believe it is unfounded, send us your reasons; we will reassess and restore the content if you are right. Our decisions are not final and you may appeal them.</p>

<h2>6. Misuse of the reporting process</h2>
<p>We may decline to act on reports used to silence a competitor or gain an unfair advantage, and we may block addresses that send systematically unfounded reports.</p>

<h2>7. Our position as a hosting provider</h2>
<p>As a hosting provider we are under no obligation to monitor the content we host in advance. Our responsibility is to run the process described above in respect of content whose unlawfulness has been brought to our attention. This reflects Article 5 of Turkish Law No. 5651 and the hosting-provider provisions of the EU Digital Services Act.</p>
