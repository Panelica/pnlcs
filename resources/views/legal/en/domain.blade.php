<h2>1. Rules that bind you directly</h2>
<p>Registering a domain creates a relationship not only with us but with the registrar and the registry operating the extension. As a result:</p>
<ul>
    <li>ICANN's policies for registered name holders,</li>
    <li>the rules of the registry operating your extension (Verisign for .com, TRABIS for .tr, and so on),</li>
    <li>the Uniform Domain-Name Dispute-Resolution Policy (UDRP) and, where applicable, the URS</li>
</ul>
<p>are directly binding on you. When these rules change we must follow them; they are outside our control.</p>

<h2>2. Registration data and accuracy</h2>
<p>ICANN requires registered name holders to provide <strong>accurate, complete and current</strong> contact information.</p>
<ul>
    <li>You must update your details promptly when they change.</li>
    <li>Deliberately providing false information, or failing to respond to a verification request within <strong>15 days</strong>, results in suspension of the domain. This is an obligation ICANN places on us; it is not at our discretion.</li>
    <li>Some extensions require verification of your email address. If you do not respond to the verification email, the domain stops resolving.</li>
</ul>

<h2>3. WHOIS / RDDS</h2>
<p>Some of your registration data may be published in the public lookup services (WHOIS/RDDS) operated by the registry and registrar. Which fields appear varies by extension and by the data protection rules in force; for natural persons covered by the GDPR, contact details are redacted for most extensions.</p>
<p>Where the extension supports it, you may request privacy/proxy protection. Note that such protection can be lifted in response to a lawful request or a UDRP proceeding.</p>

