<h2>6. Transfers</h2>
<p><strong>Transferring to us:</strong> the domain must be at least 60 days old, unlocked, and you must hold the authorisation (EPP/Auth) code from your current provider. A transfer usually adds one year to the registration term.</p>
<p><strong>Transferring away:</strong> you may move your domain to another provider at any time. You can obtain your EPP code from the client area or request it from us; <strong>we supply it within 5 days and charge nothing for it.</strong> We do not block transfers where you have no unpaid invoice.</p>
<p>ICANN rules prohibit transfers within <strong>60 days</strong> of registration or of a previous transfer.</p>

<h2>7. Disputes</h2>
<p>A UDRP proceeding may be brought against you alleging that your domain infringes a trade mark. Such proceedings are run not by us but by dispute resolution providers approved by ICANN, such as WIPO.</p>
<p>Where a UDRP panel or a court orders the transfer, cancellation or locking of a domain, we are obliged to implement it. For .tr extensions, the dispute resolution mechanism operated by TRABIS applies.</p>

<h2>8. Name servers</h2>
<p>You may change your domain's name servers at any time. By default ours are set. Name server changes take <strong>24–48 hours</strong> to propagate across the internet, and that propagation is not under our control.</p>

