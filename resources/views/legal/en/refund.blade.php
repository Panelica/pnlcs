<h2>3. After the window: mid-term cancellation</h2>
<p>Once the refund window has passed you may cancel at any time. In that case:</p>
<ul>
    <li>the service <strong>continues to the end of the period you have paid for</strong> and closes at the end of it;</li>
    <li>there is <strong>no pro-rata refund</strong> for the unused portion, though we can hold the remaining value as credit on your account for use against other services;</li>
    <li>no invoice is issued for the following period.</li>
</ul>

<h2>4. Where the fault is ours</h2>
<p>In the following cases we refund the unused portion pro rata, even after the refund window has passed:</p>
<ul>
    <li>we cannot deliver the service you bought, or cannot provide the features we advertised;</li>
    <li>we terminate the service unilaterally through no fault of yours;</li>
    <li>we have fallen far short of the uptime commitment in the <a href="{{ route('legal.show', 'sla') }}">SLA</a> in a given month and the service credit does not cover your loss.</li>
</ul>

