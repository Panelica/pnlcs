<h2>1.a. Your statutory right of withdrawal</h2>
<p>If you are a consumer, Turkish Law No. 6502 and the Distance Contracts Regulation separately give you a <strong>14-day right of withdrawal</strong>. Article 15 of that Regulation, however, excludes services performed instantly in electronic form and services whose performance began with your consent — which covers hosting and domains, since they are provisioned the moment your order is confirmed.</p>
<p>That is precisely why we offer the guarantee above: we commit by contract to a trial-and-change-your-mind window the law does not oblige us to give. The 30 days on an annual plan is more than twice the statutory fourteen.</p>
<p>Where a statutory right of withdrawal does arise on the facts and no exclusion applies, nothing in this policy restricts it; whichever is more favourable to you applies.

